function currentLang() {
  return localStorage.getItem(CMMS_LANG_KEY) === 'ar' ? 'ar' : 'en';
}

function t(text) {
  const key = String(text ?? '');
  if (currentLang() !== 'ar') return key;
  return Object.prototype.hasOwnProperty.call(CMMS_AR, key) ? CMMS_AR[key] : key;
}

function applyTexts() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-option]').forEach((el) => {
    el.textContent = t(el.dataset.i18nOption);
  });
  document.querySelectorAll('[data-set-lang]').forEach((button) => {
    button.classList.toggle('active', button.dataset.setLang === currentLang());
  });
}

function setLanguage(lang, silent) {
  const next = lang === 'ar' ? 'ar' : 'en';
  localStorage.setItem(CMMS_LANG_KEY, next);
  document.documentElement.lang = next;
  document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
  applyTexts();
  if (!silent) document.dispatchEvent(new CustomEvent('cmms-language', { detail: next }));
}

function bindLanguageSwitch() {
  document.querySelectorAll('[data-set-lang]').forEach((button) => {
    if (button.dataset.langBound) return;
    button.dataset.langBound = '1';
    button.addEventListener('click', () => setLanguage(button.dataset.setLang));
  });
}

window.t = t;
window.currentLang = currentLang;
window.setLanguage = setLanguage;
window.applyLanguage = () => setLanguage(currentLang(), true);
setLanguage(currentLang(), true);
bindLanguageSwitch();
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang(), true);
  bindLanguageSwitch();
});
